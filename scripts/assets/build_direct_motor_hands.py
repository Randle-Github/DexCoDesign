"""Build a uniform direct-motor URDF library for every registered hand.

The output actuation grammar has exactly two movable-joint classes:

* active: an independent direct actuator, represented by a SimpleTransmission;
* passive: an affine mimic of one active joint.

There are no unconstrained passive joints.  URDF mimic relations are retained
and flattened.  MJCF joint equalities become affine mimics.  A tendon acting
on several joints is approximated by one active master and range-normalized
mimic followers.  The original assets are never modified.
"""

